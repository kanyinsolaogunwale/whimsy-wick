  /** Real advance width: each glyph is pitch*px wide. */
  WW.textWidth = (str, px = 1, pitch = 6) => str.length * pitch * px;

  /**
   * Draw `str` with the 5×7 font at glyph-pixel size `px`, anchored at
   * the top-left of the pen position. Returns advance width.
   */
  WW.fillText = (ctx, str, x, y, px = 1, color = '#4a3524', pitch = 6) => {
    ctx.save();
    ctx.fillStyle = color;
    for (let i = 0; i < str.length; i++) {
      const rows = GLYPHS[str[i]] || GLYPHS['?'];
      for (let r = 0; r < rows.length; r++) {
        const row = rows[r];
        for (let c = 0; c < row.length; c++) {
          if (row[c] === '1') ctx.fillRect(x + i * pitch * px + c * px, y + r * px, px, px);
        }
      }
    }
    ctx.restore();
    return str.length * pitch * px;
  };

  /* -------------------------------------------------------------- *
   *  Canvas texture helpers                                         *
   * -------------------------------------------------------------- */
  WW.canvas = (w, h) => {
    const c = document.createElement('canvas');
    c.width = w; c.height = h;
    return c;
  };

  /** Round-rect path helper (canvas2d). */
  WW.rr = (ctx, x, y, w, h, r) => {
    r = Math.min(r, w / 2, h / 2);
    ctx.beginPath();
    ctx.moveTo(x + r, y);
    ctx.arcTo(x + w, y, x + w, y + h, r);
    ctx.arcTo(x + w, y + h, x, y + h, r);
    ctx.arcTo(x, y + h, x, y, r);
    ctx.arcTo(x, y, x + w, y, r);
    ctx.closePath();
  };

  /**
   * Static texture cache: WW.tex(key, w, h, drawFn), drawn once, memoised.
   * Returns { canvas, texture }. Call WW.warmTextures(THREE) to upload.
   */
  const _tex = new Map();
  WW.tex = (key, w, h, drawFn) => {
    if (_tex.has(key)) return _tex.get(key);
    const c = WW.canvas(w, h);
    drawFn(c.getContext('2d'), w, h);
    const entry = { canvas: c, texture: null };
    _tex.set(key, entry);
    return entry;
  };
  WW.texAll = () => Array.from(_tex.values());
  WW.clearTextures = () => _tex.clear();
